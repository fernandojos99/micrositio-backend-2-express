-- transcript: resúmenes de reuniones. La escribe y lee la Lambda de
-- transcripciones, no el backend. created_at llega sin zona horaria.
CREATE TABLE IF NOT EXISTS transcript (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  proyecto text,
  resumen text,
  resumen_estructurado jsonb,
  created_at timestamp DEFAULT now()
);

-- Historial de conversaciones del agente: el esquema estándar del
-- PostgresSaver de LangGraph (lo usa la Lambda del agente, no el backend).
CREATE TABLE IF NOT EXISTS checkpoint_migrations (
  v integer PRIMARY KEY
);
CREATE TABLE IF NOT EXISTS checkpoints (
  thread_id text NOT NULL,
  checkpoint_ns text NOT NULL DEFAULT '',
  checkpoint_id text NOT NULL,
  parent_checkpoint_id text,
  type text,
  checkpoint jsonb NOT NULL,
  metadata jsonb NOT NULL DEFAULT '{}',
  PRIMARY KEY (thread_id, checkpoint_ns, checkpoint_id)
);
CREATE TABLE IF NOT EXISTS checkpoint_blobs (
  thread_id text NOT NULL,
  checkpoint_ns text NOT NULL DEFAULT '',
  channel text NOT NULL,
  version text NOT NULL,
  type text NOT NULL,
  blob bytea,
  PRIMARY KEY (thread_id, checkpoint_ns, channel, version)
);
CREATE TABLE IF NOT EXISTS checkpoint_writes (
  thread_id text NOT NULL,
  checkpoint_ns text NOT NULL DEFAULT '',
  checkpoint_id text NOT NULL,
  task_id text NOT NULL,
  idx integer NOT NULL,
  channel text NOT NULL,
  type text,
  blob bytea NOT NULL,
  task_path text NOT NULL DEFAULT '',
  PRIMARY KEY (thread_id, checkpoint_ns, checkpoint_id, task_id, idx)
);
CREATE INDEX IF NOT EXISTS checkpoints_thread_id_idx ON checkpoints (thread_id);
CREATE INDEX IF NOT EXISTS checkpoint_blobs_thread_id_idx ON checkpoint_blobs (thread_id);
CREATE INDEX IF NOT EXISTS checkpoint_writes_thread_id_idx ON checkpoint_writes (thread_id);

