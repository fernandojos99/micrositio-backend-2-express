-- Completa el esquema de la base LOCAL (copia de marzo de 2026) con lo que
-- producción añadió después y el código actual necesita.
--
-- Solo aditivo: CREATE TABLE / ADD COLUMN con IF NOT EXISTS. No borra ni
-- modifica nada existente y se puede volver a ejecutar sin efecto.
--
--   psql -h localhost -U micrositio -d micrositio -v ON_ERROR_STOP=1 -1 -f local/completar-esquema.sql
--
-- Procedencia de los tipos: producción no expone su DDL con la clave anon, así
-- que se dedujeron de valores reales leídos por la API REST, de los esquemas
-- Zod y del uso en los repositorios. Donde producción solo tiene NULL
-- (empleado.image) se asume text, que es lo que guarda usuarios.image (una URL).
-- Las restricciones son las mínimas que el código necesita: mejor aceptar algo
-- que producción aceptaría que rechazarlo.
--
-- Las tablas nuevas quedan VACÍAS: esto trae la estructura, no los datos.

-- ---------------------------------------------------------------------------
-- Tablas nuevas
-- ---------------------------------------------------------------------------

-- habilidadesRepositorio: filtra por id_empleado, actualiza y borra por
-- id_habilidad. habilidadService exige nombre_habilidad.
CREATE TABLE IF NOT EXISTS public.habilidades (
    id_habilidad      integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_empleado       integer NOT NULL REFERENCES public.empleado (id_empleado),
    nombre_habilidad  text    NOT NULL,
    nivel             text
);
CREATE INDEX IF NOT EXISTS habilidades_id_empleado_idx ON public.habilidades (id_empleado);

-- servicioRepository: lee y ordena por id. Campos del servicioSchema (Zod).
CREATE TABLE IF NOT EXISTS public.servicio (
    id             integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nombre         text    NOT NULL,
    descripcion    text,
    objetivo       text,
    entregables    text,
    precio_aprox   numeric,
    horas_totales  numeric,
    categoria      text,
    created_at     timestamp with time zone DEFAULT now(),
    updated_at     timestamp with time zone DEFAULT now()
);

-- sesionRepository.crear inserta SOLO {id_empleado, thread_id}: todo lo demás
-- necesita valor por defecto. thread_id se busca con maybeSingle(), así que
-- tiene que ser único. id_empleado admite NULL porque un VISITANTE puede no
-- tener empleado asociado.
CREATE TABLE IF NOT EXISTS public.sesion (
    id_sesion    integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_empleado  integer REFERENCES public.empleado (id_empleado),
    thread_id    text    NOT NULL UNIQUE,
    titulo       text,
    activo       boolean NOT NULL DEFAULT true,
    created_at   timestamp with time zone NOT NULL DEFAULT now(),
    updated_at   timestamp with time zone NOT NULL DEFAULT now()
);
CREATE INDEX IF NOT EXISTS sesion_id_empleado_idx ON public.sesion (id_empleado);

