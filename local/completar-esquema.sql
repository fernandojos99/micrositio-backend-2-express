-- 2026-09-14 — Etapas de proyecto (maqueta) y rol ADMIN
-- ---------------------------------------------------------------------------
-- Solo aditivo y reejecutable.

-- Rol ADMIN: es EDITOR + aprobar proyectos. Se amplía el CHECK (no se borra
-- ninguna fila) y el usuario `admin` pasa a ese tipo.
ALTER TABLE usuarios DROP CONSTRAINT IF EXISTS usuarios_tipo_check;
ALTER TABLE usuarios ADD CONSTRAINT usuarios_tipo_check
  CHECK (tipo IN ('EDITOR', 'VISITANTE', 'ADMIN'));
UPDATE usuarios SET tipo = 'ADMIN' WHERE alias = 'admin' AND tipo <> 'ADMIN';

-- Estado de las 5 etapas de un proyecto. `datos` guarda el brief, la propuesta
-- editable y lo capturado en cada pestaña; `es_maqueta` recuerda que esto se
-- llenó con la maqueta y aún falta implementarlo de verdad.
CREATE TABLE IF NOT EXISTS proyecto_etapa (
  id_proyecto integer PRIMARY KEY REFERENCES proyecto(id_proyecto) ON DELETE CASCADE,
  etapa_actual text NOT NULL DEFAULT 'BRIEF'
    CHECK (etapa_actual IN ('BRIEF', 'PLAN', 'EJECUCION', 'IDEACION', 'RESULTADOS')),
  datos jsonb NOT NULL DEFAULT '{}'::jsonb,
  aprobado_por uuid REFERENCES usuarios(id_usuario),
  aprobado_en timestamptz,
  es_maqueta boolean NOT NULL DEFAULT true,
  created_at timestamptz NOT NULL DEFAULT now(),
  updated_at timestamptz NOT NULL DEFAULT now()
);

-- Cards propuestas por el plan de trabajo: existen pero no se muestran en el
-- resto de la aplicación hasta que el ADMIN aprueba el proyecto. El default
-- deja visible todo lo que ya existía.
ALTER TABLE testing_card ADD COLUMN IF NOT EXISTS es_borrador boolean NOT NULL DEFAULT false;
ALTER TABLE learning_card ADD COLUMN IF NOT EXISTS es_borrador boolean NOT NULL DEFAULT false;

-- Métricas de un accionable (pestaña Ideación), con la misma forma que las de
-- testing card: nombre + operador + criterio, y resultado que se llena después.
CREATE TABLE IF NOT EXISTS metrica_accionable (
  id_metrica_accionable integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  id_accionable integer NOT NULL REFERENCES accionable(id_accionable) ON DELETE CASCADE,
  nombre text NOT NULL,
  operador text,
  criterio text,
  resultado text,
  created_at timestamptz NOT NULL DEFAULT now(),
  updated_at timestamptz NOT NULL DEFAULT now()
);
CREATE INDEX IF NOT EXISTS metrica_accionable_id_accionable_idx ON metrica_accionable (id_accionable);

-- ---------------------------------------------------------------------------
-- 2026-09-15 — Brief del procesador de transcripts
-- ---------------------------------------------------------------------------
-- Solo aditivo y reejecutable.

-- Lo que devuelve el procesador de transcripts al pulsar Ejecutar, atado al
-- proyecto. Es distinto de la tabla `transcript` de más arriba: aquella la
-- escribe la Lambda, guarda el nombre del proyecto como texto libre (ninguna
-- de sus filas coincide con un proyecto real) y este backend no la toca.
--
-- Una fila por proyecto, como proyecto_etapa: cada Ejecutar sustituye al
-- anterior mediante upsert. De los archivos solo se guarda la referencia; el
-- binario vive en disco, en el bucket brief-docs, servido en /archivos.
-- Todo es nulable salvo la clave: el .pptx debe poder subirse sin haber
-- pulsado Ejecutar.
CREATE TABLE IF NOT EXISTS proyecto_brief (
  id_proyecto integer PRIMARY KEY REFERENCES proyecto(id_proyecto) ON DELETE CASCADE,
  nombre_proyecto text,
  transcript_id text,
  url text,
  resumen text,
  resumen_estructurado jsonb,
  origen text CHECK (origen IN ('texto', 'docx')),
  archivo_nombre text,
  archivo_url text,
  archivo_tipo text,
  archivo_tamano integer,
  pptx_nombre text,
  pptx_url text,
  pptx_tamano integer,
  ejecutado_en timestamptz,
  created_at timestamptz NOT NULL DEFAULT now(),
  updated_at timestamptz NOT NULL DEFAULT now()
);
